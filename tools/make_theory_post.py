def render(post):
    S = []
    S.append('<!doctype html><html lang="ko"><meta charset="utf-8">')
    S.append('<title>이론 시리즈 초안 %02d — %s</title>' % (post['n'], post['title']))
    S.append('<style>%s</style>' % P.CSS)
    S.append('<h1>부동산 사이클 시리즈 %02d편</h1>' % post['n'])
    S.append('<p class="hint">[복사] → 스마트에디터에 붙여넣기 → 이미지 끌어놓기 → 발행. '
             '카테고리는 <b>부동산 사이클</b>, 주제는 <b>부동산</b>으로 두세요.</p>')
    S.append('<section class="draft"><h2>%s</h2>' % post['title'])
    S.append(P.rival_panel('부동산 사이클'))
    S.append(P.field('제목', 't1', P.esc(post['title']), 't'))
    # 이미지마다 사이트로 가는 문을 단다. 캡처는 삽화가 아니라 "아공맵에 오면
    # 이걸 직접 볼 수 있다"는 증거이고, 블로그의 목적이 사이트 유입이다
    # (2026-08-16 사용자). 맨 끝 링크 하나면 거기까지 읽은 사람만 넘어간다.
    # 링크를 갈라 두는 이유: 같은 곳으로 세 번 보내면 세 번째는 안 눌린다.
    _S = sync_stats()
    body = post['body'].strip() % {
        'link': link('아공맵 부동산 사이클 리포트 보기'),
        'cycle': link('고리별 검증 결과 보기'),
        'zone': link('우리 동네 공급은 어떤가 — 시도별 리포트',
                     path='/zone/', camp='zone_from_cycle'),
        # exp는 그 자체가 <p>…</p> 여러 개다. 본문 템플릿에서 <p>%(exp)s</p>로
        # 감싸면 <p> 안에 <p>가 들어가 빈 문단이 생긴다(2026-09-10 클립보드
        # 실측: <p></p><p><br></p> 가 두 군데). 감싸지 않고 넣고, 비어 있을
        # 때만 자리 표시자를 <p>로 감싼다.
        'exp': post.get('exp') or ('<p>%s</p>' % EXP_PLACEHOLDER),
        # 동조성 관련 수치는 전부 사이트에서 읽어 넣는다(2026-09-12 재산정으로
        # 15곳 → 14곳, 평균 0.71 → 0.73, 서울 0.58 → 0.55로 바뀌었다).
        'sync_table': sync_table(),
        'sync_n': _S['n'],
        'sync_avg': ('%.2f' % _S['avg']),
        'sync_top2': _S['top2'],
        'sync_topv': ('%.1f' % _S['top']['corr']),
        'sync_lowv': ('%.2f' % _S['low']['corr']),

    }
    S.append(P.field('본문', 'b1', body))
    S.append(P.tagfield(post.get('tags', []) + TAGS))
    for f, spot in post['imgs']:
        S.append('<p class="note">📎 <code>drafts\\%s</code> → 본문의 '
                 '[여기에 %s] 자리</p>' % (f, spot))
    S.append('<p class="note">네이버는 외부 이미지 주소를 그대로 쓰지 않으므로 '
             '파일을 직접 올려야 합니다. 이미지마다 아래 캡션을 달아 주세요 — '
             '이미지만 있으면 검색이 읽을 게 없습니다.</p>')
    S.append('</section>')
    S.append('<p class="hint">⚠️ 사이트 /cycle/ 페이지와 같은 문장을 쓰면 유사문서로 '
             '묶입니다. 고쳐 쓰실 때도 사이트 문장을 그대로 가져오지 마세요.</p>')
    # 이론 글은 특히 위험한 자리다 — 개념을 설명하다 보면 "누가 이렇게 말했다"를
    # 적고 싶어진다. 근거는 사실만으로 온전하다(2026-08-15 리뷰 지적).
    S.append(P.SOURCE_CHECK)
    S.append('<script>%s</script></html>' % P.JS)
    return '\n'.join(S)


def main(argv):
    n = int(argv[0]) if argv and argv[0].isdigit() else 1
    post = next((p for p in POSTS if p['n'] == n), None)
    if not post:
        raise SystemExit('%d편은 아직 안 썼다. POSTS에 추가할 것.' % n)
    if not os.path.isdir(OUT):
        os.makedirs(OUT)
    path = os.path.join(OUT, 'theory-%02d.html' % n)
    io.open(path, 'w', encoding='utf-8', newline='\n').write(render(post))
    print('이론 초안 생성: %s' % os.path.relpath(path, ROOT))
    print('  %s' % post['title'])
    # 열지 않는다 — 재생성이 잦다. 볼 때만 --open.
    if '--open' in argv:
        try:
            import webbrowser
            webbrowser.open('file:///' + path.replace('\\', '/'))
        except Exception:
            pass
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
